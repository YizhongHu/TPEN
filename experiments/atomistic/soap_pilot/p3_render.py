_HOOKE2_PHYSICAL_SYSTEM_ID = planned_physical_system_ids()["hooke2"]
_PBS_STAGE1_SHA256 = "52c83a78a5f65b3b6af929ff3b524fa06ccca00baf1f76ddff669d6e202acebc"
_PBS_STAGE1_PIN_COMMIT = "8857d9ea3119b195684fa0cb69beaaebb676dd6c"
_MISSING = object()


class P3RenderError(ValueError):
    """Raised when a P3 packet cannot be admitted without weakening a guard."""


@dataclass(frozen=True)
class AdmittedCommand:
    """One admitted row and the command generated by the Stage-1 launcher."""

    row: Mapping[str, Any]
    command: str
    config: Any


@dataclass(frozen=True)
class EvalTemplate:
    """Rendered eval configuration awaiting a real SOAP100 publication."""

    rendered: RenderedConfig
    source_sha: str
    results_root: str
    run_id: str
    device: str
    output_dir: str
    checkpoint_step: int = 100


def admit_row_and_command(
    row: Mapping[str, Any], *, python: str, checkout_root: str,
) -> AdmittedCommand:
    """Admit one materialized row through the real Stage-1 gateway.

    The same row bytes are loaded and revalidated immediately before command
    generation.  ``command_for_row`` is the sole owner of driver argv shape.
    """

    try:
        validate_row(row, expected_kind=row.get("kind"))
        config_path = Path(row["row_extension"]["rendered_config"]["path"])
        rendered_values = yaml.safe_load(config_path.read_bytes())
        _audit_packet_recipe(row, rendered_values, python=python, checkout_root=checkout_root)
        admitted = validate_gateway_binding(
            binding=_binding_token(row), expected_kinds={row["kind"]},
        )
        config, admission = load_materialized_config(row, expected_kind=row["kind"])
        validate_materialized_admission(config, row, admission, check_file=True)
        command = command_for_row(row, python=python, checkout_root=checkout_root)
    except Exception as exc:  # normalize all pre-launch refusal paths
        raise P3RenderError(f"row admission refused: {exc}") from exc
    if admitted.get("kind") != row["kind"]:
        raise P3RenderError("gateway admitted a different row kind")
    return AdmittedCommand(row=row, command=command, config=config)


def render_r2_train_packet(
    *, output_dir: str | Path, results_root: str, source_sha: str,
    device: str = "cuda", profiles: tuple[PilotProfile, ...] = R2_PROFILES,
) -> dict[str, ComposedRow]:
    """Render the four singleton R2 train rows with unique run identities."""

    names = [profile.name for profile in profiles]
    if len(names) != len(set(names)):
        raise P3RenderError("R2 packet contains duplicate profile names")
    packet = {
        profile.name: render_profile(
            profile, output_dir=output_dir, results_root=results_root,
            source_sha=source_sha, run_id=f"soap_p3_{profile.name}", device=device,
        )
        for profile in profiles
    }
    for profile in profiles:
        composed = packet[profile.name]
        _audit_packet_recipe(
            composed.row,
            composed.rendered.values,
            python=sys.executable,
            checkout_root=str(Path(__file__).resolve().parents[3]),
        )
    rows = [entry.row for entry in packet.values()]
    if len({row["run_id"] for row in rows}) != len(rows):
        raise P3RenderError("R2 packet run identities are not singleton")
    return packet


def render_eval_template(
    *, output_dir: str | Path, results_root: str, source_sha: str,
    run_id: str = "soap_p3_eval_100", device: str = "cuda",
) -> EvalTemplate:
    """Render an eval template without inventing a checkpoint or parent row."""

    config, _ = _materialize_eval(
        results_root=results_root, run_id=run_id,
        checkpoint_dir="/P3/UNPUBLISHED/SOAP100", checkpoint_file="model.pt",
        source_sha=source_sha, device=device,
    )
    # The placeholder is a template marker only; it is never passed to
    # ``make_eval_row`` or ``command_for_row``.
    rendered = _write_yaml(Path(output_dir) / "r2-soap-eval-100.template.yaml", config)
    return EvalTemplate(rendered, source_sha, results_root, run_id, device, str(Path(output_dir)))


def finalize_eval_row(
    template: EvalTemplate, *, train_row: Mapping[str, Any],
    publication: CheckpointEvidence, parent: ParentJoin,
    checkpoint_dir: str | Path, stream: int = 0, draws: int = 256,
) -> dict[str, Any]:
    """Finalize an eval row only from a complete, named SOAP100 publication.

    ``model.pt`` and ``COMPLETE`` must be real files under the named checkpoint
    directory, and their identities must agree with the publication evidence.
    """

    if not _is_approved_soap100_row(train_row):
        raise P3RenderError("SOAP100 eval requires the approved SOAP optimizer family and recipe")
    if publication.step != template.checkpoint_step:
        raise P3RenderError("SOAP publication is not checkpoint-100")
    if not publication.publication_id or publication.publication_id in {"zero", "duplicate", "missing"}:
        raise P3RenderError("SOAP100 publication identity is missing or non-unique")
    try:
        publication.validate(expected_step=template.checkpoint_step)
    except RowContractError as exc:
        raise P3RenderError(f"SOAP publication evidence is invalid: {exc}") from exc
    checkpoint_root = Path(checkpoint_dir).resolve()
    try:
        train_config = yaml.safe_load(
            Path(train_row["row_extension"]["rendered_config"]["path"]).read_bytes()
        )
        run = train_config["run"]
        parent_run_dir = (
            Path(train_row["results_root"])
            / train_row["experiment_name"]
            / train_row["sector"]
            / train_row["run_id"]
        ).resolve()
        if (
            run.get("root") != train_row["results_root"]
            or run.get("run_id") != train_row["run_id"]
            or Path(run.get("dir", "")).resolve() != parent_run_dir
        ):
            raise P3RenderError("SOAP100 parent config is not bound to the admitted train row")
    except (KeyError, OSError, TypeError, yaml.YAMLError) as exc:
        raise P3RenderError("SOAP100 parent train config cannot be admitted") from exc
    expected_checkpoint_root = parent_run_dir / "checkpoints" / f"step_{template.checkpoint_step:06d}"
    if checkpoint_root != expected_checkpoint_root:
        raise P3RenderError("SOAP100 checkpoint is not the admitted parent step directory")
    model = checkpoint_root / "model.pt"
    complete = checkpoint_root / "COMPLETE"
    if not model.is_file() or not complete.is_file():
        raise P3RenderError("SOAP100 publication is not COMPLETE with model.pt")
    named_model = Path(publication.files["model.pt"]).resolve()
    named_complete = Path(publication.files["COMPLETE"]).resolve()
    if named_model != model or named_complete != complete:
        raise P3RenderError("publication named files do not match checkpoint directory")
    model_bytes = model.read_bytes()
    complete_bytes = complete.read_bytes()
    if not complete_bytes:
        raise P3RenderError("SOAP100 COMPLETE publication marker is empty")
    model_sha = hashlib.sha256(model_bytes).hexdigest()
    if model_sha != publication.model_sha256:
        raise P3RenderError("SOAP100 model.pt hash disagrees with publication")
    if not publication.complete:
        raise P3RenderError("SOAP100 publication is not COMPLETE")
    if publication.parent_run_id is not None and publication.parent_run_id != train_row.get("run_id"):
        raise P3RenderError("SOAP100 publication parent run identity does not match train row")
    if publication.parent_output_dir is not None:
        if Path(publication.parent_output_dir).resolve() != parent_run_dir:
            raise P3RenderError("SOAP100 parent output metadata disagrees with the admitted parent")
    if parent.row_id != train_row.get("row_id"):
        raise P3RenderError("SOAP100 publication parent does not match train row")
    try:
        final_path = Path(template.output_dir) / "r2-soap-eval-100.yaml"
        if final_path.exists():
            raise P3RenderError("eval destination already exists")
        config, _ = _materialize_eval(
            results_root=template.results_root, run_id=template.run_id,
            checkpoint_dir=str(checkpoint_root), checkpoint_file=str(model),
            source_sha=template.source_sha, device=template.device,
        )
        rendered = _write_yaml(final_path, config)
        return make_eval_row(
            train_row=train_row, parent=parent, checkpoint=publication,
            rendered=rendered,
            row_base={
                "run_id": template.run_id, "stream": stream, "draws": draws,
                "config": "configs/hooke2/eval.yaml",
                "seed": 6348702091350892190, "walkers": 4096,
                "checkpoint_dir": str(checkpoint_root),
                "expected_physical_system_id": _HOOKE2_PHYSICAL_SYSTEM_ID,
            },
        )
    except (RowContractError, KeyError, TypeError) as exc:
        raise P3RenderError(f"SOAP100 parent/publication join refused: {exc}") from exc


def render_pbs_audit() -> dict[str, Any]:
    """Return the named PBS contract evidence without editing the wrapper."""

    wrapper = Path(__file__).resolve().parents[1] / "stage1" / "polaris" / "pbs_stage1.sh"
    text = wrapper.read_text(encoding="utf-8")
    actual_sha = hashlib.sha256(text.encode("utf-8")).hexdigest()
    if actual_sha != _PBS_STAGE1_SHA256:
        raise P3RenderError(
            "PBS guard evidence refused: wrapper digest drift: "
            f"expected {_PBS_STAGE1_SHA256} from {_PBS_STAGE1_PIN_COMMIT}, got {actual_sha}"
        )
    lines = text.splitlines()

    def source_lines(function: str) -> tuple[tuple[int, str], ...]:
        """Return one shell function's actual numbered source lines."""

        start = next((index for index, line in enumerate(lines) if line == f"{function}() {{"), None)
        if start is None:
            raise P3RenderError(f"PBS evidence missing function: {function}")
        end = next(
            (index for index in range(start + 1, len(lines))
             if re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*\(\) \{", lines[index])),
            len(lines),
        )
        return tuple((index + 1, lines[index]) for index in range(start, end))

    def quote_checks(function: str, needles: tuple[str, ...]) -> dict[str, Any]:
        body = source_lines(function)
        checks: list[str] = []
        for needle in needles:
            match = next(((number, line.strip()) for number, line in body if needle in line), None)
            if match is None:
                raise P3RenderError(f"PBS evidence missing {function} check: {needle}")
            checks.append(f"{match[0]}: {match[1]}")
        return {
            "function": function,
            "line_range": [body[0][0], body[-1][0]],
            "checks": tuple(checks),
        }

    # Derive the environment contract from the wrapper's declarations and
    # require_value calls rather than duplicating an echoed list in P3.
    expected_env = ("MODE", "SOURCE_SHA", "CHECKOUT_ROOT", "UV_CACHE_DIR", "RESULTS_ROOT", "SELECTED_ROW", "APPROVAL_ID", "EXPECTED_QUEUE")
    env_evidence: dict[str, str] = {}
    for name in expected_env:
        match = next(
            ((index + 1, line.strip()) for index, line in enumerate(lines)
             if re.search(rf"\b{name}\b", line) and ("=" in line or "require_value" in line)),
            None,
        )
        if match is None:
            raise P3RenderError(f"PBS environment declaration missing: {name}")
        env_evidence[name] = f"{match[0]}: {match[1]}"

    admission = quote_checks("admit_selected_row", (
        "require_value SELECTED_ROW",
        '[[ "$SELECTED_ROW" == /* ]] || die',
        'if [[ "$DRY_EXEC" == 1 ]]; then',
        'assert_contained_path "$RESULTS_ROOT/plan" "$RESULTS_ROOT" RESULTS_PLAN',
        'assert_contained_path "$ADMITTED_ROW" "$RESULTS_ROOT" ADMITTED_ROW',
    ))
    command = quote_checks("run_command_for_row", (
        'if [[ "$DRY_EXEC" == 1 ]]; then',
        'printf \'DRY_EXEC compute=SKIPPED',
        '[[ "$DRY_EXEC" != 1 ]] || die',
        "from experiments.atomistic.stage1.launch import command_for_row",
        "argv = shlex.split(command_for_row(row, python=python, checkout_root=checkout))",
        "completed = subprocess.run(argv, cwd=checkout, env=os.environ)",
    ))
    output = quote_checks("run_mode", (
        'log="$RESULTS_ROOT/logs/row-${row_id}-${PBS_JOBID}.log"',
        'status="$RESULTS_ROOT/logs/row-${row_id}-${PBS_JOBID}.status"',
        'assert_contained_path "$log" "$destination_root" log',
        'assert_contained_path "$status" "$destination_root" status',
        'run_command_for_row "$row" "$gpu" "$cpu_set" "$core_count" "$log" "$status"',
    ))
    guards = {
        name: quote_checks(name, needles)
        for name, needles in {
            "assert_contained_path": ("if ! canonical=", "canonical.relative_to(root.resolve())"),
            "validate_selected_row": ("if row.get(\"kind\") != kind", "if row.get(\"source_sha\") != source_sha", "row results_root is outside wrapper RESULTS_ROOT"),
            "assert_pbs_context": ("require_value PBS_JOBID", "require_value PBS_QUEUE", "require_value EXPECTED_QUEUE", '[[ "$PBS_QUEUE" == "$EXPECTED_QUEUE" ]]'),
            "guard_gpus": ('[[ "${#gpu_lines[@]}" == 4 ]]', 'CUDA_VISIBLE_DEVICES="$i"', '[[ "$count" == 1 ]]'),
            "derive_cpu_layout": ('[[ "${#layout_lines[@]}" == 3 ]]', 'LINEAGE_CPU_SETS[$lineage]="$cpu_set"', 'LINEAGE_CORE_COUNTS[$lineage]="$core_count"'),
        }.items()
    }
    evidence = {**guards, "admit_selected_row": admission, "run_command_for_row": command, "run_mode": output}
    return {
        "wrapper": str(wrapper),
        "wrapper_sha256": _PBS_STAGE1_SHA256,
        "wrapper_pin_commit": _PBS_STAGE1_PIN_COMMIT,
        "env": expected_env,
        "env_evidence": env_evidence,
        "outputs": (output["checks"][0], output["checks"][1]),
        "command_owner": "stage1.launch.command_for_row",
        "argv": command["checks"][4],
        "log": output["checks"][0],
        "status": output["checks"][1],
        "lr4_guards": tuple(guards),
        "guard_evidence": evidence,
    }


def recipe_diff(expected: Mapping[str, Any], actual: Mapping[str, Any], *, allowed_paths: set[str] | frozenset[str] = frozenset()) -> dict[str, tuple[Any, Any]]:
    """Return changed leaf paths, retaining only recipe-level identity."""

    changes: dict[str, tuple[Any, Any]] = {}

    def visit(left: Any, right: Any, path: str) -> None:
        if isinstance(left, Mapping) and isinstance(right, Mapping):
            for key in sorted(set(left) | set(right)):
                child = f"{path}.{key}" if path else str(key)
                visit(left[key] if key in left else _MISSING, right[key] if key in right else _MISSING, child)
            return
        if left is _MISSING or right is _MISSING:
            changes[path] = (left, right)
            return
        if isinstance(left, list) and isinstance(right, list):
            if left != right:
                changes[path] = (left, right)
            return
        if type(left) is not type(right) or left != right:
            changes[path] = (left, right)

    visit(expected, actual, "")
    return {path: pair for path, pair in changes.items() if not any(path == allowed or path.startswith(f"{allowed}.") for allowed in allowed_paths)}


def fail_closed_recipe_diff(expected: Mapping[str, Any], actual: Mapping[str, Any], *, allowed_paths: set[str] | frozenset[str] = frozenset()) -> None:
    """Refuse any rendered recipe difference outside enumerated paths."""

    changes = recipe_diff(expected, actual, allowed_paths=allowed_paths)
    if changes:
        raise P3RenderError(f"unenumerated recipe diff: {sorted(changes)}")


def _normalise_recipe(value: Any, *, results_root: str, run_id: str, parent_run_dir: str | None = None) -> Any:
    """Normalize only declared packet destinations before recipe comparison."""

    if isinstance(value, Mapping):
        return {
            key: _normalise_recipe(
                child, results_root=results_root, run_id=run_id, parent_run_dir=parent_run_dir
            )
            for key, child in value.items()
        }
    if isinstance(value, list):
        return [
            _normalise_recipe(
                child, results_root=results_root, run_id=run_id, parent_run_dir=parent_run_dir
            )
            for child in value
        ]
    if isinstance(value, str):
        normalized = value
        if parent_run_dir is not None:
            normalized = normalized.replace(parent_run_dir, "/__P3_PARENT__")
        return normalized.replace(results_root, "<RESULTS_ROOT>").replace(run_id, "<RUN_ID>")
    return value


def _profile_for_row(row: Mapping[str, Any], config: Mapping[str, Any]) -> str | None:
    """Return the independently reviewed recipe matching the supplied row."""

    if row.get("kind") == "eval":
        recipe = APPROVED_RECIPES["eval-soap-100"]
        profile = recipe["profile"]
        if (
            row.get("checkpoint") != profile["checkpoint"]
            or row.get("walkers") != profile["walkers"]
            or row.get("draws") != profile["draws"]
        ):
            return None
        return "eval-soap-100"
    if row.get("kind") != "train":
        return None
    optimizer = config.get("optimizer")
    if not isinstance(optimizer, Mapping):
        return None
    candidates = []
    for name, recipe in APPROVED_RECIPES.items():
        if recipe["kind"] != "train":
            continue
        profile = recipe["profile"]
        expected_optimizer = recipe["config"].get("optimizer", {})
        if (
            optimizer.get("_target_") == expected_optimizer.get("_target_")
            and profile["updates"] == row.get("updates")
            and profile["walkers"] == row.get("walkers")
            and profile["checkpoint_steps"] == row.get("checkpoint_steps")
        ):
            candidates.append(name)
    return candidates[0] if len(candidates) == 1 else None


def _runner_bindings(row: Mapping[str, Any], *, command: str) -> Mapping[str, Any]:
    """Return the concrete env/argv/output binding audited for one row."""

    run_dir = Path(row["results_root"]) / row["experiment_name"] / row["sector"] / row["run_id"]
    return {
        "env": {
            "MODE": row["kind"],
            "SOURCE_SHA": row["source_sha"],
            "CHECKOUT_ROOT": "<CHECKOUT_ROOT>",
            "UV_CACHE_DIR": "<UV_CACHE_DIR>",
            "RESULTS_ROOT": row["results_root"],
            "SELECTED_ROW": row["row_id"],
            "APPROVAL_ID": "<APPROVAL_ID>",
            "EXPECTED_QUEUE": "test",
        },
        "argv": command,
        "output": {
            "run_dir": str(run_dir),
            "inputs": str(Path(row["results_root"]) / "inputs"),
            "checkpoint_dir": str(run_dir / "checkpoints"),
            "log": str(Path(row["results_root"]) / "logs" / f"row-{row['row_id']}-${{PBS_JOBID}}.log"),
            "status": str(Path(row["results_root"]) / "logs" / f"row-{row['row_id']}-${{PBS_JOBID}}.status"),
        },
    }


def _audit_packet_recipe(row: Mapping[str, Any], config: Mapping[str, Any], *, python: str, checkout_root: str) -> Mapping[str, Any]:
    """Gate a rendered packet against the frozen recipe and concrete bindings."""

    recipe_name = _profile_for_row(row, config)
    if recipe_name is None:
        raise P3RenderError("rendered packet does not match an approved recipe for its row kind")
    recipe = APPROVED_RECIPES[recipe_name]
    parent_run_dir = None
    if row["kind"] == "eval":
        parent_run_dir = str(Path(row["checkpoint_dir"]).resolve().parents[1])
    normalized = _normalise_recipe(
        config, results_root=row["results_root"], run_id=row["run_id"], parent_run_dir=parent_run_dir
    )
    expected = recipe["config"]
    fail_closed_recipe_diff(
        expected,
        normalized,
        allowed_paths=set(recipe["allowed_paths"]),
    )
    command = command_for_row(row, python=python, checkout_root=checkout_root)
    bindings = _runner_bindings(row, command=command)
    binding = recipe["binding"]
    if Path(row["row_extension"]["rendered_config"]["path"]).name != binding["input_name"]:
        raise P3RenderError("rendered packet input destination is not the approved row output")
    if _binding_token(row) not in command:
        raise P3RenderError("runner argv is not bound to the admitted row")
    expected_script = f"experiments/atomistic/stage1/{binding['script']}"
    if bindings["env"]["MODE"] != binding["mode"] or expected_script not in command:
        raise P3RenderError("concrete packet env/argv binding disagrees with the approved recipe")
    if not bindings["output"]["log"].endswith(".log") or not bindings["output"]["status"].endswith(".status"):
        raise P3RenderError("concrete packet env/argv/output binding is incomplete")
    return bindings


def _is_approved_soap100_row(row: Mapping[str, Any]) -> bool:
    """Check the actual rendered row, not a caller-supplied family label."""

    if row.get("kind") != "train" or row.get("updates") != 100 or row.get("walkers") != 512 or row.get("checkpoint_steps") != [0, 100]:
        return False
    path = Path(row["row_extension"]["rendered_config"]["path"])
    try:
        values = yaml.safe_load(path.read_bytes())
    except (OSError, yaml.YAMLError):
        return False
    optimizer = values.get("optimizer") if isinstance(values, Mapping) else None
    return isinstance(optimizer, Mapping) and optimizer.get("_target_") == "tpen.training.SOAP" and optimizer.get("lr") == 0.005 and optimizer.get("betas") == [0.95, 0.95] and optimizer.get("precondition_frequency") == 10 and optimizer.get("max_precond_dim") == 128 and optimizer.get("precondition_1d") is False and optimizer.get("correct_bias") is True


