class P3RenderError(ValueError):
    """Raised when a P3 packet cannot be admitted without weakening a guard."""


@dataclass(frozen=True)
class AdmittedCommand:
    """One admitted row and the command generated by the Stage-1 launcher."""

    row: Mapping[str, Any]
    command: str
    config: Any


@dataclass(frozen=True)
class EvalTemplate:
    """Rendered eval configuration awaiting a real SOAP100 publication."""

    rendered: RenderedConfig
    source_sha: str
    results_root: str
    run_id: str
    device: str
    output_dir: str
    checkpoint_step: int = 100


def admit_row_and_command(
    row: Mapping[str, Any], *, python: str, checkout_root: str,
) -> AdmittedCommand:
    """Admit one materialized row through the real Stage-1 gateway.

    The same row bytes are loaded and revalidated immediately before command
    generation.  ``command_for_row`` is the sole owner of driver argv shape.
    """

    try:
        validate_row(row, expected_kind=row.get("kind"))
        admitted = validate_gateway_binding(
            binding=_binding_token(row), expected_kinds={row["kind"]},
        )
        config, admission = load_materialized_config(row, expected_kind=row["kind"])
        validate_materialized_admission(config, row, admission, check_file=True)
        command = command_for_row(row, python=python, checkout_root=checkout_root)
    except Exception as exc:  # normalize all pre-launch refusal paths
        raise P3RenderError(f"row admission refused: {exc}") from exc
    if admitted.get("kind") != row["kind"]:
        raise P3RenderError("gateway admitted a different row kind")
    return AdmittedCommand(row=row, command=command, config=config)


def render_r2_train_packet(
    *, output_dir: str | Path, results_root: str, source_sha: str,
    device: str = "cuda", profiles: tuple[PilotProfile, ...] = R2_PROFILES,
) -> dict[str, ComposedRow]:
    """Render the four singleton R2 train rows with unique run identities."""

    names = [profile.name for profile in profiles]
    if len(names) != len(set(names)):
        raise P3RenderError("R2 packet contains duplicate profile names")
    packet = {
        profile.name: render_profile(
            profile, output_dir=output_dir, results_root=results_root,
            source_sha=source_sha, run_id=f"soap_p3_{profile.name}", device=device,
        )
        for profile in profiles
    }
    rows = [entry.row for entry in packet.values()]
    if len({row["run_id"] for row in rows}) != len(rows):
        raise P3RenderError("R2 packet run identities are not singleton")
    return packet


def render_eval_template(
    *, output_dir: str | Path, results_root: str, source_sha: str,
    run_id: str = "soap_p3_eval_100", device: str = "cuda",
) -> EvalTemplate:
    """Render an eval template without inventing a checkpoint or parent row."""

    config, _ = _materialize_eval(
        results_root=results_root, run_id=run_id,
        checkpoint_dir="/P3/UNPUBLISHED/SOAP100", checkpoint_file="model.pt",
        source_sha=source_sha, device=device,
    )
    # The placeholder is a template marker only; it is never passed to
    # ``make_eval_row`` or ``command_for_row``.
    rendered = _write_yaml(Path(output_dir) / "r2-soap-eval-100.template.yaml", config)
    return EvalTemplate(rendered, source_sha, results_root, run_id, device, str(Path(output_dir)))


def finalize_eval_row(
    template: EvalTemplate, *, train_row: Mapping[str, Any],
    publication: CheckpointEvidence, parent: ParentJoin,
    checkpoint_dir: str | Path, stream: int = 0, draws: int = 256,
) -> dict[str, Any]:
    """Finalize an eval row only from a complete, named SOAP100 publication.

    ``model.pt`` and ``COMPLETE`` must be real files under the named checkpoint
    directory, and their identities must agree with the publication evidence.
    """

    if publication.step != template.checkpoint_step:
        raise P3RenderError("SOAP publication is not checkpoint-100")
    if not publication.publication_id or publication.publication_id in {"zero", "duplicate", "missing"}:
        raise P3RenderError("SOAP100 publication identity is missing or non-unique")
    checkpoint_root = Path(checkpoint_dir).resolve()
    model = checkpoint_root / "model.pt"
    complete = checkpoint_root / "COMPLETE"
    if not model.is_file() or not complete.is_file():
        raise P3RenderError("SOAP100 publication is not COMPLETE with model.pt")
    model_sha = hashlib.sha256(model.read_bytes()).hexdigest()
    if model_sha != publication.model_sha256:
        raise P3RenderError("SOAP100 model.pt hash disagrees with publication")
    if not publication.complete:
        raise P3RenderError("SOAP100 publication is not COMPLETE")
    if parent.row_id != train_row.get("row_id"):
        raise P3RenderError("SOAP100 publication parent is not the named train row")
    try:
        final_path = Path(template.output_dir) / "r2-soap-eval-100.yaml"
        if final_path.exists():
            raise P3RenderError("eval destination already exists")
        config, _ = _materialize_eval(
            results_root=template.results_root, run_id=template.run_id,
            checkpoint_dir=str(checkpoint_root), checkpoint_file=str(model),
            source_sha=template.source_sha, device=template.device,
        )
        rendered = _write_yaml(final_path, config)
        return make_eval_row(
            train_row=train_row, parent=parent, checkpoint=publication,
            rendered=rendered,
            row_base={
                "run_id": template.run_id, "stream": stream, "draws": draws,
                "config": "configs/hooke2/eval.yaml",
                "seed": 6348702091350892190, "walkers": 4096,
                "checkpoint_dir": str(checkpoint_root),
            },
        )
    except (RowContractError, KeyError, TypeError) as exc:
        raise P3RenderError(f"SOAP100 parent/publication join refused: {exc}") from exc


def render_pbs_audit() -> dict[str, Any]:
    """Return the named PBS contract evidence without editing the wrapper."""

    wrapper = Path(__file__).resolve().parents[1] / "stage1" / "polaris" / "pbs_stage1.sh"
    text = wrapper.read_text(encoding="utf-8")
    # Derive the environment contract from the wrapper's declarations rather
    # than duplicating an echoed list in the P3 implementation.
    required_env = tuple(re.findall(r"^([A-Z][A-Z0-9_]*)=\"\$\{\1:-\}\"", text, re.MULTILINE))
    expected_env = {"MODE", "SOURCE_SHA", "CHECKOUT_ROOT", "UV_CACHE_DIR", "RESULTS_ROOT", "SELECTED_ROW", "APPROVAL_ID", "EXPECTED_QUEUE"}
    if not expected_env <= set(required_env):
        raise P3RenderError(f"PBS environment declarations incomplete: {sorted(expected_env - set(required_env))}")
    required_outputs = ("$RESULTS_ROOT/logs/row-", "checkpoints")
    missing = [token for token in (*required_env, *required_outputs, "command_for_row") if token not in text]
    if missing:
        raise P3RenderError(f"PBS contract evidence missing: {missing}")
    command_form = re.search(r"command_for_row\(row, python=python, checkout_root=checkout\)", text)
    log_form = re.search(r'\$RESULTS_ROOT/logs/row-\$\{row_id\}-\$\{PBS_JOBID\}\.log', text)
    status_form = re.search(r'\$RESULTS_ROOT/logs/row-\$\{row_id\}-\$\{PBS_JOBID\}\.status', text)
    lr4_guards = tuple(token for token in ("assert_pbs_context", "assert_selected_row", "assert_contained_path", "DRY_EXEC", "EXPECTED_QUEUE") if token in text)
    if command_form is None or log_form is None or status_form is None or len(lr4_guards) != 5:
        raise P3RenderError("PBS argv/output/LR-4 guard evidence is incomplete")
    return {"wrapper": str(wrapper), "env": required_env, "outputs": required_outputs, "command_owner": "stage1.launch.command_for_row", "argv": command_form.group(0), "log": log_form.group(0), "status": status_form.group(0), "lr4_guards": lr4_guards}


def recipe_diff(expected: Mapping[str, Any], actual: Mapping[str, Any], *, allowed_paths: set[str] | frozenset[str] = frozenset()) -> dict[str, tuple[Any, Any]]:
    """Return changed leaf paths, retaining only recipe-level identity."""

    changes: dict[str, tuple[Any, Any]] = {}

    def visit(left: Any, right: Any, path: str) -> None:
        if isinstance(left, Mapping) and isinstance(right, Mapping):
            for key in sorted(set(left) | set(right)):
                visit(left.get(key), right.get(key), f"{path}.{key}" if path else str(key))
            return
        if isinstance(left, list) and isinstance(right, list):
            if left != right:
                changes[path] = (left, right)
            return
        if left != right:
            changes[path] = (left, right)

    visit(expected, actual, "")
    return {path: pair for path, pair in changes.items() if not any(path == allowed or path.startswith(f"{allowed}.") for allowed in allowed_paths)}


def fail_closed_recipe_diff(expected: Mapping[str, Any], actual: Mapping[str, Any], *, allowed_paths: set[str] | frozenset[str] = frozenset()) -> None:
    """Refuse any rendered recipe difference outside enumerated paths."""

    changes = recipe_diff(expected, actual, allowed_paths=allowed_paths)
    if changes:
        raise P3RenderError(f"unenumerated recipe diff: {sorted(changes)}")


