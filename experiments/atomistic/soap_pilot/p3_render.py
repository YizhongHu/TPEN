"""Fail-closed P3 render packets for the SOAP optimizer pilot.

P3 owns the concrete R2 train packet and the *template* for the strict SOAP
evaluation.  A final evaluation row is deliberately a separate operation: it
requires a named, complete checkpoint publication and the actual singleton
train parent.  This module never synthesizes an evaluation parent and never
builds a driver command by hand.
"""

