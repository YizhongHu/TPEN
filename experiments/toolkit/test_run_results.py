"""P8 toolkit reader tests.

The fixture is generated by the executor-side helper with:
``PYTHONPATH=executor/src python executor/tests/helpers/p8_manifest_fixture.py experiments/toolkit/fixtures/run-manifest-v2.json``.
That command is the provenance/regeneration path; this test intentionally
imports only the toolkit reader and standard-library test helpers.
``run-manifest-v1.json`` preserves the original P3 fixture bytes for the
backward-compatibility case.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest

from experiments.toolkit.run_results import ManifestRefusal, read


FIXTURE = Path(__file__).parent / "fixtures" / "run-manifest-v2.json"
FIXTURE_V1 = Path(__file__).parent / "fixtures" / "run-manifest-v1.json"


def _materialized_manifest(tmp_path: Path, *, extra_attempt: bool = False) -> tuple[Path, str]:
    payload = json.loads(FIXTURE.read_text(encoding="utf-8"))
    output_dir = tmp_path / "attempt-1"
    core_dir = output_dir / "core"
    checkpoint_dir = core_dir / "checkpoint" / "step_000001"
    checkpoint_dir.mkdir(parents=True)
    payload["attempts"][0]["output_dir"] = str(output_dir)
    payload["attempts"][0]["start_receipt"]["output_dir"] = str(output_dir)
    payload["attempts"][0]["outcome_receipt"]["output_dir"] = str(output_dir)
    payload["segments"][0]["checkpoint_dir"] = str(checkpoint_dir)
    if extra_attempt:
        second = json.loads(json.dumps(payload["attempts"][0]))
        second["attempt_id"] = "attempt-2"
        second["output_dir"] = str(tmp_path / "attempt-2")
        second["start_receipt"]["attempt_id"] = "attempt-2"
        second["start_receipt"]["output_dir"] = second["output_dir"]
        second["outcome_receipt"]["attempt_id"] = "attempt-2"
        second["outcome_receipt"]["output_dir"] = second["output_dir"]
        payload["attempts"].append(second)
    path = tmp_path / "run-manifest.json"
    path.write_text(json.dumps(payload), encoding="utf-8")
    return path, str(core_dir)


def test_p8_reader_selects_exactly_once_and_preserves_unselected_attempts(tmp_path: Path) -> None:
    path, core_dir = _materialized_manifest(tmp_path, extra_attempt=True)

    def inspect(run_dir: str | Path) -> dict[str, object]:
        assert str(run_dir) == core_dir
        return {
            "verdict": "completed",
            "checkpoint": {
                "checkpoint_dir": str(tmp_path / "attempt-1" / "core" / "checkpoint" / "step_000001"),
                "schema_version": 1,
                "next_iteration": 1,
                "completed_updates": 1,
            },
        }

    result = read(path, inspect)
    assert len(result.chains) == 1
    assert [segment.attempt_id for segment in result.chains[0].segments] == ["attempt-1"]
    assert [attempt.attempt_id for attempt in result.preserved_attempts] == ["attempt-2"]
    assert result.preserved_attempts[0].reason == "not-selected"
    assert all(attempt.attempt_id not in {segment.attempt_id for chain in result.chains for segment in chain.segments} for attempt in result.preserved_attempts)


def test_p8_reader_refuses_core_evidence_mismatch(tmp_path: Path) -> None:
    path, _ = _materialized_manifest(tmp_path)
    with pytest.raises(ManifestRefusal, match="disagrees"):
        read(path, lambda _: {"verdict": "completed", "checkpoint": {"checkpoint_dir": "wrong", "schema_version": 1, "next_iteration": 1, "completed_updates": 1}})


@pytest.mark.parametrize(
    ("field", "value"),
    [
        pytest.param("task_id", "other-task", id="task"),
        pytest.param("attempt_id", "attempt-2", id="attempt"),
        pytest.param("output_dir", "/runs/group-1/task-a/attempt-2", id="output-dir"),
    ],
)
def test_p8_reader_refuses_outcome_binding_mismatch(
    tmp_path: Path, field: str, value: str
) -> None:
    path, _ = _materialized_manifest(tmp_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    # Keep the group digest and all segment/start fields consistent so only
    # the outcome-to-manifest binding check can refuse this selected attempt.
    payload["attempts"][0]["outcome_receipt"][field] = value
    path.write_text(json.dumps(payload), encoding="utf-8")

    with pytest.raises(ManifestRefusal, match="manifest attempt disagrees with its outcome receipt"):
        read(
            path,
            lambda _: {
                "verdict": "completed",
                "checkpoint": {
                    "checkpoint_dir": str(tmp_path / "attempt-1" / "core" / "checkpoint" / "step_000001"),
                    "schema_version": 1,
                    "next_iteration": 1,
                    "completed_updates": 1,
                },
            },
        )


def _write_segment_mutation(tmp_path: Path, mutation: str) -> Path:
    path, _ = _materialized_manifest(tmp_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    segment = payload["segments"][0]
    if mutation == "gap":
        segment["predecessor_checkpoint"] = str(tmp_path / "missing-checkpoint")
    elif mutation == "replayed":
        second = json.loads(json.dumps(payload["attempts"][0]))
        second["attempt_id"] = "attempt-2"
        second["output_dir"] = str(tmp_path / "attempt-2")
        second["start_receipt"]["attempt_id"] = "attempt-2"
        second["start_receipt"]["output_dir"] = second["output_dir"]
        second["outcome_receipt"]["attempt_id"] = "attempt-2"
        second["outcome_receipt"]["output_dir"] = second["output_dir"]
        payload["attempts"].append(second)
        replay = dict(segment)
        replay["attempt_id"] = "attempt-2"
        replay["checkpoint_dir"] = str(tmp_path / "attempt-2" / "core" / "checkpoint" / "step_000001")
        replay["predecessor_checkpoint"] = segment["checkpoint_dir"]
        payload["segments"].append(replay)
    elif mutation == "wrong-predecessor":
        second = json.loads(json.dumps(payload["attempts"][0]))
        second["attempt_id"] = "attempt-2"
        second["output_dir"] = str(tmp_path / "attempt-2")
        second["start_receipt"]["attempt_id"] = "attempt-2"
        second["start_receipt"]["output_dir"] = second["output_dir"]
        second["outcome_receipt"]["attempt_id"] = "attempt-2"
        second["outcome_receipt"]["output_dir"] = second["output_dir"]
        payload["attempts"].append(second)
        continuation = dict(segment)
        continuation["attempt_id"] = "attempt-2"
        continuation["checkpoint_dir"] = str(tmp_path / "attempt-2" / "core" / "checkpoint" / "step_000002")
        continuation["predecessor_checkpoint"] = str(tmp_path / "wrong-checkpoint")
        continuation["next_iteration"] = 2
        continuation["completed_updates"] = 2
        payload["segments"].append(continuation)
    elif mutation == "uncommitted":
        segment["attempt_id"] = "uncommitted-attempt"
    elif mutation == "failed":
        payload["attempts"][0]["outcome_receipt"]["status"] = "failed"
    elif mutation == "foreign-task":
        segment["task_id"] = "other-task"
    path.write_text(json.dumps(payload), encoding="utf-8")
    return path


def test_p8_reader_rejects_gap(tmp_path: Path) -> None:
    with pytest.raises(ManifestRefusal, match="fresh start"):
        read(_write_segment_mutation(tmp_path, "gap"), lambda _: None)


def test_p8_reader_rejects_replayed_non_increasing_segment(tmp_path: Path) -> None:
    with pytest.raises(ManifestRefusal, match="strictly increasing"):
        read(_write_segment_mutation(tmp_path, "replayed"), lambda _: None)


def test_p8_reader_rejects_wrong_predecessor(tmp_path: Path) -> None:
    with pytest.raises(ManifestRefusal, match="predecessor"):
        read(_write_segment_mutation(tmp_path, "wrong-predecessor"), lambda _: None)


def test_p8_reader_rejects_segment_on_uncommitted_attempt(tmp_path: Path) -> None:
    with pytest.raises(ManifestRefusal, match="unknown attempt"):
        read(_write_segment_mutation(tmp_path, "uncommitted"), lambda _: None)


def test_p8_reader_rejects_segment_on_failed_attempt(tmp_path: Path) -> None:
    with pytest.raises(ManifestRefusal, match="completed attempt"):
        read(_write_segment_mutation(tmp_path, "failed"), lambda _: None)


def test_p8_reader_rejects_foreign_task_segment(tmp_path: Path) -> None:
    with pytest.raises(ManifestRefusal, match="task differs"):
        read(_write_segment_mutation(tmp_path, "foreign-task"), lambda _: None)


def test_p8_reader_accepts_v1_as_empty_chain(tmp_path: Path) -> None:
    path = tmp_path / "v1.json"
    path.write_bytes(FIXTURE_V1.read_bytes())
    result = read(path, lambda _: pytest.fail("v1 has no accepted segments"))
    assert result.chains == ()
    assert len(result.preserved_attempts) == 1


@pytest.mark.parametrize("mutation", ["unknown-schema", "duplicate", "scalar-segments"])
def test_p8_reader_named_rejection_paths(tmp_path: Path, mutation: str) -> None:
    payload = json.loads(FIXTURE.read_text(encoding="utf-8"))
    if mutation == "unknown-schema":
        payload["schema"] = "tpen-executor/run-manifest-v9"
    elif mutation == "duplicate":
        payload["segments"].append(dict(payload["segments"][0]))
    else:
        payload["segments"] = "not-a-sequence"
    path = tmp_path / f"{mutation}.json"
    path.write_text(json.dumps(payload), encoding="utf-8")
    with pytest.raises(ManifestRefusal):
        read(path, lambda _: None)
