def test_p8_reader_accepts_optional_placement_receipt_and_surfaces_it(tmp_path: Path) -> None:
    path, _ = _materialized_manifest(tmp_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    payload["attempts"][0]["placement_receipt"] = _placement_receipt(payload["attempts"][0]["output_dir"])
    path.write_text(json.dumps(payload), encoding="utf-8")

    result = read(
        path,
        lambda _: {
            "verdict": "completed",
            "checkpoint": {
                "checkpoint_dir": str(tmp_path / "attempt-1" / "core" / "checkpoint" / "step_000001"),
                "schema_version": 1,
                "next_iteration": 1,
                "completed_updates": 1,
            },
        },
    )
    placement = result.chains[0].segments[0].placement_receipt
    assert placement is not None
    assert placement["schema"] == "tpen-executor/science-placement-receipt-v1"
    assert placement["attempt_id"] == "attempt-1"
    assert placement["child"]["proc_start_ticks"] == 55
    assert placement["comparison"] == {"host": "matched", "affinity": "matched", "device": "unavailable"}


def test_p8_reader_accepts_v2_and_reconciles_loud_v3_verdict(tmp_path: Path) -> None:
    path, _ = _materialized_manifest(tmp_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    placement = _placement_receipt_v2(payload["attempts"][0]["output_dir"], qualified=False)
    payload["attempts"][0]["placement_receipt"] = placement
    payload["schema"] = "tpen-executor/run-manifest-v3"
    payload["placement_verdict"] = {
        "status": "unqualified",
        "science_acceptance": "not-accepted",
        "message": "GPU PLACEMENT UNQUALIFIED: H-v2/science acceptance MUST NOT accept these GPU segments.",
        "unqualified_gpu_segments": [{"task_id": "task-a", "attempt_id": "attempt-1", "reason_class": "telemetry-unavailable", "reason": "telemetry-unavailable: nvidia-smi-missing"}],
    }
    path.write_text(json.dumps(payload), encoding="utf-8")
    result = read(path, lambda _: {"verdict": "completed", "checkpoint": {"checkpoint_dir": str(tmp_path / "attempt-1" / "core" / "checkpoint" / "step_000001"), "schema_version": 1, "next_iteration": 1, "completed_updates": 1}})
    assert result.chains[0].segments[0].placement_receipt["verdict"]["reason_class"] == "telemetry-unavailable"
    assert result.placement_unqualified
    assert "GPU PLACEMENT UNQUALIFIED" in result.placement_verdict["message"]


@pytest.mark.parametrize("mutation", ["unknown-version", "closed-key", "non-finite"])
def test_p8_reader_refuses_v2_wire_mutations_before_inspection(tmp_path: Path, mutation: str) -> None:
    path, _ = _materialized_manifest(tmp_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    placement = _placement_receipt_v2(payload["attempts"][0]["output_dir"], qualified=True)
    if mutation == "unknown-version":
        placement["schema"] = "tpen-executor/science-placement-receipt-v9"
    elif mutation == "closed-key":
        placement["host_mapping"]["unexpected"] = True
    else:
        placement["gpu_sampler"]["monotonic_start"] = float("nan")
    payload["attempts"][0]["placement_receipt"] = placement
    path.write_text(json.dumps(payload, allow_nan=True), encoding="utf-8")
    with pytest.raises(ManifestRefusal):
        read(path, lambda _: pytest.fail("v2 wire mutation must refuse before inspection"))


@pytest.mark.parametrize("mutation", ["extra-key", "bad-child-pid", "bad-gpu-sequence"])
def test_p8_reader_refuses_malformed_placement_receipt(tmp_path: Path, mutation: str) -> None:
    path, _ = _materialized_manifest(tmp_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    placement = _placement_receipt(payload["attempts"][0]["output_dir"])
    if mutation == "extra-key":
        placement["unexpected"] = True
    elif mutation == "bad-child-pid":
        placement["child"]["pid"] = "1234"
    else:
        placement["gpu"]["samples"] = "not-a-sequence"
    payload["attempts"][0]["placement_receipt"] = placement
    path.write_text(json.dumps(payload), encoding="utf-8")

    with pytest.raises(ManifestRefusal, match="placement"):
        read(path, lambda _: pytest.fail("malformed placement must be rejected before inspection"))


@pytest.mark.parametrize(
    ("field", "value"),
    [
        pytest.param("task_id", "other-task", id="task"),
        pytest.param("attempt_id", "attempt-2", id="attempt"),
        pytest.param("output_dir", "/runs/group-1/task-a/attempt-2", id="output-dir"),
    ],
)
def test_p8_reader_refuses_outcome_binding_mismatch(
    tmp_path: Path, field: str, value: str
) -> None:
    path, _ = _materialized_manifest(tmp_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    # Keep the group digest and all segment/start fields consistent so only
    # the outcome-to-manifest binding check can refuse this selected attempt.
    payload["attempts"][0]["outcome_receipt"][field] = value
    path.write_text(json.dumps(payload), encoding="utf-8")

    with pytest.raises(ManifestRefusal, match="manifest attempt disagrees with its outcome receipt"):
        read(
            path,
            lambda _: {
                "verdict": "completed",
                "checkpoint": {
                    "checkpoint_dir": str(tmp_path / "attempt-1" / "core" / "checkpoint" / "step_000001"),
                    "schema_version": 1,
                    "next_iteration": 1,
                    "completed_updates": 1,
                },
            },
        )


def _write_segment_mutation(tmp_path: Path, mutation: str) -> Path:
    path, _ = _materialized_manifest(tmp_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    segment = payload["segments"][0]
    if mutation == "gap":
        segment["predecessor_checkpoint"] = str(tmp_path / "missing-checkpoint")
    elif mutation == "replayed":
        second = json.loads(json.dumps(payload["attempts"][0]))
        second["attempt_id"] = "attempt-2"
        second["output_dir"] = str(tmp_path / "attempt-2")
        second["start_receipt"]["attempt_id"] = "attempt-2"
        second["start_receipt"]["output_dir"] = second["output_dir"]
        second["outcome_receipt"]["attempt_id"] = "attempt-2"
        second["outcome_receipt"]["output_dir"] = second["output_dir"]
        payload["attempts"].append(second)
        replay = dict(segment)
        replay["attempt_id"] = "attempt-2"
        replay["checkpoint_dir"] = str(tmp_path / "attempt-2" / "core" / "checkpoint" / "step_000001")
        replay["predecessor_checkpoint"] = segment["checkpoint_dir"]
        payload["segments"].append(replay)
    elif mutation == "wrong-predecessor":
        second = json.loads(json.dumps(payload["attempts"][0]))
        second["attempt_id"] = "attempt-2"
        second["output_dir"] = str(tmp_path / "attempt-2")
        second["start_receipt"]["attempt_id"] = "attempt-2"
        second["start_receipt"]["output_dir"] = second["output_dir"]
        second["outcome_receipt"]["attempt_id"] = "attempt-2"
        second["outcome_receipt"]["output_dir"] = second["output_dir"]
        payload["attempts"].append(second)
        continuation = dict(segment)
        continuation["attempt_id"] = "attempt-2"
        continuation["checkpoint_dir"] = str(tmp_path / "attempt-2" / "core" / "checkpoint" / "step_000002")
        continuation["predecessor_checkpoint"] = str(tmp_path / "wrong-checkpoint")
        continuation["next_iteration"] = 2
        continuation["completed_updates"] = 2
        payload["segments"].append(continuation)
    elif mutation == "uncommitted":
        segment["attempt_id"] = "uncommitted-attempt"
    elif mutation == "failed":
        payload["attempts"][0]["outcome_receipt"]["status"] = "failed"
    elif mutation == "foreign-task":
        segment["task_id"] = "other-task"
    path.write_text(json.dumps(payload), encoding="utf-8")
    return path


def test_p8_reader_rejects_gap(tmp_path: Path) -> None:
    with pytest.raises(ManifestRefusal, match="fresh start"):
        read(_write_segment_mutation(tmp_path, "gap"), lambda _: None)


