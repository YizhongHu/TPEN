def test_p8_reader_accepts_v1_as_empty_chain(tmp_path: Path) -> None:
    path = tmp_path / "v1.json"
    path.write_bytes(FIXTURE_V1.read_bytes())
    result = read(path, lambda _: pytest.fail("v1 has no accepted segments"))
    assert result.chains == ()
    assert len(result.preserved_attempts) == 1


@pytest.mark.parametrize("mutation", ["unknown-schema", "duplicate", "scalar-segments"])
def test_p8_reader_named_rejection_paths(tmp_path: Path, mutation: str) -> None:
    payload = json.loads(FIXTURE.read_text(encoding="utf-8"))
    if mutation == "unknown-schema":
        payload["schema"] = "tpen-executor/run-manifest-v9"
    elif mutation == "duplicate":
        payload["segments"].append(dict(payload["segments"][0]))
    else:
        payload["segments"] = "not-a-sequence"
    path = tmp_path / f"{mutation}.json"
    path.write_text(json.dumps(payload), encoding="utf-8")
    with pytest.raises(ManifestRefusal):
        read(path, lambda _: None)
