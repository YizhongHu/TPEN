def _write_segment_mutation(tmp_path: Path, mutation: str) -> Path:
    path, _ = _materialized_manifest(tmp_path)
    payload = json.loads(path.read_text(encoding="utf-8"))
    segment = payload["segments"][0]
    if mutation == "gap":
        segment["predecessor_checkpoint"] = str(tmp_path / "missing-checkpoint")
    elif mutation == "replayed":
        second = json.loads(json.dumps(payload["attempts"][0]))
        second["attempt_id"] = "attempt-2"
        second["output_dir"] = str(tmp_path / "attempt-2")
        second["start_receipt"]["attempt_id"] = "attempt-2"
        second["start_receipt"]["output_dir"] = second["output_dir"]
        second["outcome_receipt"]["attempt_id"] = "attempt-2"
        second["outcome_receipt"]["output_dir"] = second["output_dir"]
        payload["attempts"].append(second)
        replay = dict(segment)
        replay["attempt_id"] = "attempt-2"
        replay["checkpoint_dir"] = str(tmp_path / "attempt-2" / "core" / "checkpoint" / "step_000001")
        replay["predecessor_checkpoint"] = segment["checkpoint_dir"]
        payload["segments"].append(replay)
    elif mutation == "wrong-predecessor":
        second = json.loads(json.dumps(payload["attempts"][0]))
        second["attempt_id"] = "attempt-2"
        second["output_dir"] = str(tmp_path / "attempt-2")
        second["start_receipt"]["attempt_id"] = "attempt-2"
        second["start_receipt"]["output_dir"] = second["output_dir"]
        second["outcome_receipt"]["attempt_id"] = "attempt-2"
        second["outcome_receipt"]["output_dir"] = second["output_dir"]
        payload["attempts"].append(second)
        continuation = dict(segment)
        continuation["attempt_id"] = "attempt-2"
        continuation["checkpoint_dir"] = str(tmp_path / "attempt-2" / "core" / "checkpoint" / "step_000002")
        continuation["predecessor_checkpoint"] = str(tmp_path / "wrong-checkpoint")
        continuation["next_iteration"] = 2
